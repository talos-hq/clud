"""Render the Homebrew formula for one published clud release.

The formula installs the same direct release assets as `install.sh` (macOS
arm64/x86_64, static musl Linux arm64/x86_64), pinned by the release's
SHA256SUMS, so `brew install talos-hq/tap/clud` and `curl | sh` ship
byte-identical binaries. Homebrew owns PATH for its own prefix, so a brew
install needs no shell-startup edits.

    python -m installer.homebrew_formula <tag> <SHA256SUMS> > Formula/clud.rb

The auto-release workflow runs this after promotion and pushes the result to
talos-hq/homebrew-tap.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = "talos-hq/clud"
# (Homebrew OS block, Homebrew CPU block, release triple)
TARGETS = (
    ("on_macos", "on_arm", "aarch64-apple-darwin"),
    ("on_macos", "on_intel", "x86_64-apple-darwin"),
    ("on_linux", "on_arm", "aarch64-unknown-linux-musl"),
    ("on_linux", "on_intel", "x86_64-unknown-linux-musl"),
)
VERSION = re.compile(r"\d+\.\d+\.\d+")
DIGEST = re.compile(r"[0-9a-f]{64}")


def parse_sums(text: str) -> dict[str, str]:
    """Map asset name -> sha256 from `sha256sum` output (`./` and `*` prefixes allowed)."""
    sums: dict[str, str] = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) != 2:
            continue
        digest, name = parts
        name = name.removeprefix("*").removeprefix("./")
        if DIGEST.fullmatch(digest):
            sums[name] = digest
    return sums


def render(tag: str, sums_text: str) -> str:
    version = tag.removeprefix("v")
    if not VERSION.fullmatch(version):
        raise ValueError(f"not a stable release version: {tag!r}")
    sums = parse_sums(sums_text)
    blocks: dict[str, list[str]] = {}
    for os_block, cpu_block, triple in TARGETS:
        asset = f"clud-{version}-{triple}"
        digest = sums.get(asset)
        if digest is None:
            raise ValueError(f"{asset} is missing from SHA256SUMS")
        blocks.setdefault(os_block, []).append(
            f"    {cpu_block} do\n"
            f'      url "https://github.com/{REPO}/releases/download/{tag}/{asset}"\n'
            f'      sha256 "{digest}"\n'
            "    end\n"
        )
    platforms = "\n".join(
        f"  {os_block} do\n" + "".join(cpu) + "  end\n" for os_block, cpu in blocks.items()
    )
    return (
        "# Generated by talos-hq/clud installer/homebrew_formula.py on release.\n"
        "# Do not edit by hand: the next release overwrites this file.\n"
        "class Clud < Formula\n"
        '  desc "Fast Rust CLI for running Claude Code and Codex in YOLO mode"\n'
        f'  homepage "https://github.com/{REPO}"\n'
        # The Clud Proprietary License has no SPDX identifier.
        "  license :cannot_represent\n"
        "\n"
        f"{platforms}"
        "\n"
        "  def install\n"
        '    bin.install Dir["clud-*"].fetch(0) => "clud"\n'
        "  end\n"
        "\n"
        "  test do\n"
        '    assert_match version.to_s, shell_output("#{bin}/clud --version")\n'
        "  end\n"
        "end\n"
    )


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m installer.homebrew_formula <tag> <SHA256SUMS>", file=sys.stderr)
        return 2
    version, sums_path = argv
    try:
        sys.stdout.write(render(version, Path(sums_path).read_text(encoding="utf-8")))
    except (OSError, ValueError) as error:
        print(f"homebrew_formula: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
